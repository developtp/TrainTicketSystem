public class User {
    int passengerID;
    String name;
    int age;
    String gender;
    String phoneNumber;

    public User(int passengerID, String name, int age, String gender, String phoneNumber) {
        this.passengerID = passengerID;
        this.name = name;
        this.age = age;
        this.gender = gender;
        this.phoneNumber = phoneNumber;
    }
}